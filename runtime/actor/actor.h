/*
 * Send a message to an actor (any thread, wait-free).
 * If receiver is overloaded, mutes the current actor (sender).
 */
static inline void msActorSend(msActor* a, msMessage* msg) {
    /* Guard: null actor (DRC scope cleanup or uninitialized) */
    if (a == NULL) {
        /* I20: a CALL to a stale/dead pid must fail its reply future (BEAM {noproc})
         * so the awaiting caller unblocks instead of hanging. SEND has no reply. */
        if (msg->replyFuture != NULL) msFutureFail(msg->replyFuture, NULL);
        msMsgFree(msg);
        return;
    }
    /* Guard: don't send to dead actor (prevents use-after-free on freed mailbox) */
    if (!atomic_load_explicit(&a->alive, memory_order_acquire)) {
        if (msg->replyFuture != NULL) msFutureFail(msg->replyFuture, NULL);
        msMsgFree(msg);
        msHazardClear(a);
        return;
    }
    /* Amendment G (I16) for actor CALLs — acquire-before-visible. The reply
     * future's in-flight ref is taken HERE, on the sender's thread, before
     * the message becomes visible in the mailbox. The actor-processing
     * thread (a pool worker for scheduler N) then publishes value+finished
     * and routes the callback volley through msCompletionQueuePushOwned —
     * no worker-side incref ever touches the non-atomic rc. The drain
     * releases this ref after msFutureFireCallbacks; every fail site that
     * pops the message pairs with msMsgReplyFail's deferred release.
     * MUST stay after the two guards above: they fail the reply before any
     * ref exists, and msMsgReplyFail would over-release it. */
#if MS_FUTURE_SUBMIT_REF
    if (msg->replyFuture != NULL) {
        msIncRef(msg->replyFuture);
        ((msFutureBase*)msg->replyFuture)->crossThreadPublished = true;
    }
#endif
    bool wasEmpty = msMpscPush(&a->mailbox, msg);
    atomic_store_explicit(&a->hasWork, true, memory_order_release);

    /* Backpressure: if receiver overloaded, mute sender */
    if (msActorHasFlag(a, MS_ACTOR_OVERLOADED) && msCurrentActor != NULL) {
        msActorMute(msCurrentActor, a);
    }

    /* Pony messageq gate: schedule iff this push transitioned the mailbox empty→non-empty.
     * wasEmpty is atomic with the processing thread's markEmpty, so exactly one party (this
     * sender, or the processing thread's re-enqueue) schedules the actor — no stale-flag
     * window (the old scheduled-CAS could observe scheduled=false mid-deschedule and push the
     * actor onto a run queue while it was still being processed, so a popper popped it, failed
     * the processing CAS, and dropped it = strand), and no double-enqueue (only the
     * empty→non-empty edge pushes). A SUSPENDED actor is re-scheduled by its resume path. */
    if (wasEmpty && !msActorHasFlag(a, MS_ACTOR_SUSPENDED)) {
        atomic_store_explicit(&a->scheduled, true, memory_order_release);
        int sid = a->schedulerID;
        if (sid >= 0 && sid < msSchedulerCount) {
            msSchedRunPush(&msSchedulers[sid], a);
            /* Amortized wake: skip the wake syscall if this scheduler was already woken since
             * its last drain — O(schedulers) wakes instead of O(actors) at high send rates. */
            if (!atomic_exchange_explicit(&msSchedulers[sid].wakeAmortized, true,
                    memory_order_acq_rel)) {
                if (sid == 0) msActorWakeEventLoop();
                else msPoolWakeWorker(sid);
            }
        }
    }
    msHazardClear(a);
}

/*
 * Process up to `maxBatch` messages from the actor's mailbox.
 * Sets/clears OVERLOADED flag. Triggers unmute when caught up.
 */
static inline int msActorProcess(msActor* a, int maxBatch) {
    /* Dead actor guard — may be in run queue from before destruction */
    if (!atomic_load_explicit(&a->alive, memory_order_acquire)) return 0;
    /* CAS guard: only one thread may process this actor at a time.
     * Enables work stealing — any idle thread can safely call this. */
    bool expected = false;
    if (!atomic_compare_exchange_strong_explicit(&a->processing, &expected, true,
            memory_order_acquire, memory_order_relaxed)) {
        /* Another thread holds processing AND the actor is on a run queue (a sender's
         * wasEmpty push landed in that thread's deschedule window, between its markEmpty and
         * its processing release). We already popped it off the queue, so re-enqueue it
         * instead of dropping it: the holder's deschedule branch does NOT re-push, so a drop
         * here would strand the pending message. No double-push — the CAS only fails inside
         * that window, where the holder never re-pushes; a later pop wins the freed CAS. */
        if (a->schedulerID >= 0 && a->schedulerID < msSchedulerCount) {
            msSchedRunPush(&msSchedulers[a->schedulerID], a);
            if (a->schedulerID == 0) msActorWakeEventLoop();
            else msPoolWakeWorker(a->schedulerID);
        }
        return 0;
    }

    msActor* prevActor = msCurrentActor;
    msCurrentActor = a;

    /* Phase 5: check for pending suspension before draining mailbox */
    {
        void* sfp = atomic_load_explicit(&a->suspendedFut, memory_order_acquire);
        if (sfp != NULL) {
            msFutureBase* sf = (msFutureBase*)sfp;
            bool resumed = atomic_load_explicit(&sf->finished, memory_order_acquire);
            if (!resumed) {
                /* Still suspended — deschedule BEFORE releasing processing, or the
                 * resume callback's scheduled-CAS can never re-enqueue (strand). */
                atomic_store_explicit(&a->scheduled, false, memory_order_release);
                /* Re-check: resume may have completed between the loads — reclaim
                 * the visit (CAS back) or the mailbox stalls until the next send. */
                if (atomic_load_explicit(&sf->finished, memory_order_acquire)) {
                    bool reclaim = false;
                    resumed = atomic_compare_exchange_strong_explicit(&a->scheduled,
                        &reclaim, true, memory_order_acq_rel, memory_order_relaxed);
                }
                if (!resumed) {
                    msCurrentActor = prevActor;
                    atomic_store_explicit(&a->processing, false, memory_order_release);
                    return 0;
                }
            }
            /* Resumed: _impl stepper already completed the reply future via
             * msFutureChain. Clear suspension state, fall through to mailbox drain. */
            atomic_store_explicit(&a->suspendedFut, NULL, memory_order_release);
            a->suspendedReplyFut = NULL;
        }
    }

    /* I18 reap point: stop requested, suspension clear, we hold processing and the
     * only queue entry. The OWNER tears down and frees; a non-owner (steal) visit
     * hands the actor back so registry writes and free stay single-threaded. */
    if (atomic_load_explicit(&a->stopRequested, memory_order_acquire)) {
        int sid = a->schedulerID;
        msCurrentActor = prevActor;
        if (msMySchedulerID != sid) {
            atomic_store_explicit(&a->processing, false, memory_order_release);
            if (sid >= 0 && sid < msSchedulerCount) {
                msSchedRunPush(&msSchedulers[sid], a);
                if (sid == 0) msActorWakeEventLoop();
                else msPoolWakeWorker(sid);
            }
            return 0;
        }
        msActorDestroyWithReason(a,
            atomic_load_explicit(&a->stopReason, memory_order_relaxed));  /* frees a */
        return 0;
    }

    /* Clear BLOCKED — we're actively processing */
    msActorClearFlag(a, MS_ACTOR_BLOCKED);

    /* Reset idle timer on message receipt (Erlang: gen_server timeout resets on any message) */
    if (a->idleTimeoutMs > 0) {
        a->lastActivityMs = msMonoTimeMs();
    }

    int processed = 0;
    while (processed < maxBatch) {
        msMessage* msg = msMpscPop(&a->mailbox);
        if (msg == NULL) break;
        /* STOP signal: swallow — its scheduling job is done; the reap gate (or
         * the owner's reap scan) collects with the flag it rode in with. */
        if (msg->kind == MS_ACTOR_MSG_STOP) { processed++; continue; }
        /* System messages (kind < 0): route to onSystemMsg handler if set */
        if (msg->kind < 0 && a->onSystemMsg != NULL) {
            a->onSystemMsg(a->state, (void*)msg);
        } else {
            a->dispatch(a->state, (void*)msg);
        }
        /* Don't free msg here — MPSC pop made it the new tail stub.
         * It gets freed on the NEXT pop when a newer message takes its place. */
        processed++;
    }

    /* Scheduling decision, made WHILE HOLDING processing. Flags (heuristics) from the
     * pre-check; markEmpty is the LAST mailbox op and runs under processing so it shares the
     * single-consumer exclusion with msMpscPop (reading/CASing q->tail off-processing is the
     * two-consumer race). OVERLOADED/BLOCKED slightly-stale on a racing late message is
     * harmless. */
    bool emptyPre = msMpscIsEmpty(&a->mailbox);
    if (emptyPre) {
        if (msActorHasFlag(a, MS_ACTOR_OVERLOADED)) {
            msActorClearFlag(a, MS_ACTOR_OVERLOADED);
            msActorUnmuteAll(a);
        }
        if (a->state != NULL && msHeader(a->state)->rc > 0) {
            msActorSetFlag(a, MS_ACTOR_BLOCKED);
        }
    } else {
        msActorSetFlag(a, MS_ACTOR_OVERLOADED);
    }

    /* markEmpty: the LAST consumer op, under processing.
     *   TRUE  → truly empty → deschedule, NO re-push. A future sender's wasEmpty push
     *           re-queues it (atomic with markEmpty, so exactly one party schedules) — Pony parity.
     *   FALSE → a message is pending → re-enqueue, but DEFER the run-queue push to AFTER the
     *           processing release below, so a concurrent popper acquires processing only once
     *           we have let go (it wins the freed CAS, never drops). */
    bool reEnqueue;
    if (msMpscMarkEmpty(&a->mailbox)) {
        atomic_store_explicit(&a->hasWork, false, memory_order_release);
        atomic_store_explicit(&a->scheduled, false, memory_order_release);
        reEnqueue = false;
    } else {
        reEnqueue = true;
    }

    msCurrentActor = prevActor;
    atomic_store_explicit(&a->processing, false, memory_order_release);

    if (reEnqueue && a->schedulerID >= 0 && a->schedulerID < msSchedulerCount) {
        msSchedRunPush(&msSchedulers[a->schedulerID], a);
        if (a->schedulerID == 0) msActorWakeEventLoop();
        else msPoolWakeWorker(a->schedulerID);
    }

    msFutureReleaseFlush();
    return processed;
}

