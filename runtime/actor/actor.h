/* ===== CALL reply completion plumbing (Amendment G / I15 / I16) =====
 *
 * A CALL reply future crosses threads: the sender (owner thread) creates it,
 * the actor-processing thread (a pool worker for scheduler N) completes it,
 * and the awaiting owner reads and destroys it. Two invariants apply:
 *
 *  I16 (Amendment G): the in-flight ref is taken on the SENDER thread inside
 *  msActorSend, before the message becomes visible in the mailbox
 *  (acquire-before-visible). The completers below push via
 *  msCompletionQueuePushOwned — no worker-side incref, ever.
 *
 *  I15 (Amendment A): callbacks fire on the dispatcher DRAIN, never inline on
 *  the actor-processing worker. Before this, msMsgComplete* fired inline and
 *  the awaiting owner could observe `finished`, read the value, and destroy
 *  the future while the worker was still inside msFutureFireCallbacks —
 *  heap-use-after-free (SAN lane, 409/411, flaky under timing).
 *
 * Single-threaded builds (wasm/emcc, MS_FUTURE_SUBMIT_REF == 0) keep the old
 * inline fire: there is no second thread, so I15/I16 have nothing to order. */

/* Defined in the dispatch backends (dispatchFull.c / dispatchEmcc.c /
 * dispatchWasm.c) — declared here because actor.h sits above thread.h in
 * the include graph. */
extern void msCompletionQueuePushOwned(void* fut, bool isFail, void* error);
extern void msCompletionQueuePushReleaseBatch(void** futs, int count);

/* Publish path tail used by msMsgComplete*: the value is already stored and
 * `finished` is already release-stored (blocked waiters may read NOW — same
 * split-completion Step 1 as thread.h's spawn workers); only the callback
 * volley is routed. */
static inline void msMsgReplyDispatch(void* fut) {
#if MS_FUTURE_SUBMIT_REF
    msCompletionQueuePushOwned(fut, false, NULL);
#else
    msFutureFireCallbacks((msFutureBase*)fut);
#endif
}

/* Fail a CALL reply from any fail site (stop-during-suspend, teardown drain)
 * and release the mailbox's in-flight ref. The release is DEFERRED through
 * the completion queue (Amendment H): these sites can run on an actor-
 * processing worker, and an inline decref would race the awaiting owner on
 * the future's non-atomic rc. msFutureFail still fires inline so a blocked
 * waiter unblocks immediately (I20 {noproc}); async steppers registered on
 * the finished future re-fire through msFutureAddCallback's finished-path. */
static inline void msMsgReplyFail(void* fut) {
    if (fut == NULL) return;
    msFutureFail(fut, NULL);
#if MS_FUTURE_SUBMIT_REF
    void* f = fut;
    msCompletionQueuePushReleaseBatch(&f, 1);
#endif
}

/* ===== Phase 5: Cooperative Actor Suspension ===== */

/* Resume callback: re-enqueues actor on scheduler after spawn completion.
 * Signature matches msClosureFn (void*, ...) — called by msFutureFireCallbacks.
 * I18: the reap gate stays closed while suspendedFut is non-NULL, so every shell
 * dereference here happens-before any reap. On the stopped lane the LAST shell
 * store is the suspendedFut=NULL release; after it, only non-shell wakes. */
static inline void msActorResumeFromFut(void* rawActor, ...) {
    msActor* a = (msActor*)rawActor;
    int sid = a->schedulerID;
    if (atomic_load_explicit(&a->stopRequested, memory_order_acquire)) {
        /* Stopped lane: MS_ACTOR_SUSPENDED stays SET. It is the latch that keeps
         * senders off the wasEmpty edge, so no run-queue entry can exist when the
         * reap scan frees this shell (scheduled alone can't prove that — a
         * markEmpty/push race can overwrite a sender's scheduled=true). */
        /* R1: stop arrived during suspension — don't resume the method. Fail the
         * CALL reply so callers unblock, open the reap gate, wake the owner's
         * reap scan. Never reap here: a stale queue entry's visit may hold the
         * shell, and the reaper must be the owner scheduler. */
        if (a->suspendedReplyFut != NULL) {
            msMsgReplyFail(a->suspendedReplyFut);
        }
        a->suspendedReplyFut = NULL;
        atomic_store_explicit(&a->suspendedFut, NULL, memory_order_release);
        if (sid == 0) msActorWakeEventLoop();
        else msPoolWakeWorker(sid);
        return;
    }
    msActorClearFlag(a, MS_ACTOR_SUSPENDED);
    /* Normal resume: suspendedFut stays set — the visit clears it (gate stays
     * closed until the visit owns the shell under processing). Re-enqueue on the
     * run queue (Pony parity: CAS prevents double-push vs a concurrent send). */
    {
        bool exp = false;
        if (atomic_compare_exchange_strong_explicit(&a->scheduled, &exp, true,
                memory_order_acq_rel, memory_order_relaxed)) {
            if (sid >= 0 && sid < msSchedulerCount) {
                msSchedRunPush(&msSchedulers[sid], a);
            }
            if (sid == 0) msActorWakeEventLoop();
            else msPoolWakeWorker(sid);
        }
    }
}

/* Suspend actor: save async _impl future, register resume callback.
 * For CALL methods, replyFut is chained separately by the dispatch function. */
static inline void msActorSuspend(msActor* a, void* implFut, void* replyFut) {
    if (a == NULL) return;
    /* R1 entry check: stop won the race to the suspend point — fail the reply,
     * don't suspend, register no resume callback (no shell reference outlives
     * this call). The visit's reap gate collects on the next pass. */
    if (atomic_load_explicit(&a->stopRequested, memory_order_acquire)) {
        if (replyFut != NULL) msMsgReplyFail(replyFut);
        msHazardClear(a);
        return;
    }
    a->suspendedReplyFut = replyFut;
    atomic_store_explicit(&a->suspendedFut, implFut, memory_order_release);
    msActorSetFlag(a, MS_ACTOR_SUSPENDED);
    /* When implFut completes, resume the actor on its scheduler. From here the
     * suspendedFut gate (I18) keeps the shell reachable-safe, not the pin. */
    msFutureAddCallback(implFut, (msClosure){
        .fn = (msClosureFn)msActorResumeFromFut,
        .env = (void*)a
    });
    msHazardClear(a);
}

/* Name registry data (forward declaration — functions defined after monitors section) */
#define MS_NAME_REGISTRY_INIT_CAP 256
typedef struct { msString name; int64_t pid; } msNameEntry;
extern msNameEntry* msNameRegistry;
extern int msNameRegistryCap;
extern int msNameRegistryCount;
extern pthread_mutex_t msNameRegistryLock;

/* Lazy init: allocate on first use, zero-cost if name registry is never used */
static inline void msNameRegistryEnsure(void) {
    if (msNameRegistry != NULL) return;
    msNameRegistryCap = MS_NAME_REGISTRY_INIT_CAP;
    msNameRegistry = (msNameEntry*)calloc(msNameRegistryCap, sizeof(msNameEntry));
}

/* Grow and rehash when load factor exceeds 75%. Must hold lock. */
static inline void msNameRegistryGrow(void) {
    int oldCap = msNameRegistryCap;
    msNameEntry* oldTable = msNameRegistry;
    msNameRegistryCap = oldCap * 2;
    msNameRegistry = (msNameEntry*)calloc(msNameRegistryCap, sizeof(msNameEntry));
    msNameRegistryCount = 0;
    /* Rehash all entries into new table */
    for (int i = 0; i < oldCap; i++) {
        if (oldTable[i].pid == 0) continue;
        uint32_t h = (uint32_t)msStringHash(oldTable[i].name) & (msNameRegistryCap - 1);
        for (int k = 0; k < msNameRegistryCap; k++) {
            uint32_t s = (h + k) & (msNameRegistryCap - 1);
            if (msNameRegistry[s].pid == 0) {
                msNameRegistry[s] = oldTable[i];
                msNameRegistryCount++;
                break;
            }
        }
    }
    free(oldTable);
}

