// Writes std/core/string/caseTables.ms: the case-conversion data toUpperCase and toLowerCase read on C and the Raiser.
// The data is what the JS engine itself answers, so C and the Raiser match JS on every code point.
// Run: node tools/genStringCaseTables.mjs > std/core/string/caseTables.ms

const maxCp = 0x10ffff;
const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;
const hex = (n) => "0x" + n.toString(16).toUpperCase();

function mappings(convert) {
	const simple = [];
	const full = [];
	for (let cp = 0; cp <= maxCp; cp++) {
		if (isSurrogate(cp)) continue;
		const out = [...convert(String.fromCodePoint(cp))].map((c) => c.codePointAt(0));
		if (out.length === 1 && out[0] !== cp) simple.push([cp, out[0] - cp]);
		else if (out.length > 1) full.push([cp, ...out]);
	}
	return { simple, full };
}

// A run is codepoints lo, lo+stride, ... hi that all move by the same delta.
function runs(simple) {
	const out = [];
	for (const [cp, delta] of simple) {
		const last = out[out.length - 1];
		if (last) {
			const step = last.stride === 0 ? cp - last.hi : last.stride;
			if ((step === 1 || step === 2) && cp - last.hi === step && delta === last.delta) {
				last.hi = cp;
				last.stride = step;
				continue;
			}
		}
		out.push({ lo: cp, hi: cp, stride: 0, delta });
	}
	return out.map((r) => ({ ...r, stride: r.stride === 0 ? 1 : r.stride }));
}

function ranges(pattern) {
	const out = [];
	for (let cp = 0; cp <= maxCp; cp++) {
		if (isSurrogate(cp) || !pattern.test(String.fromCodePoint(cp))) continue;
		const last = out[out.length - 1];
		if (last && last[1] === cp - 1) last[1] = cp;
		else out.push([cp, cp]);
	}
	return out;
}

function emitTable(name, type, rows) {
	return `export const ${name}: ${type}[${rows.length}] = [\n${rows.join("\n")}\n];\n`;
}

function emitRuns(name, simple) {
	return emitTable(name, "CaseRun", runs(simple).map((r) => `\t{ lo: ${hex(r.lo)}, hi: ${hex(r.hi)}, stride: ${r.stride}, delta: ${r.delta} },`));
}

function emitFull(name, full) {
	return emitTable(name, "CaseFull", full.map(([cp, ...out]) => `\t{ cp: ${hex(cp)}, out: [${[...out, ...[0, 0, 0]].slice(0, 3).map(hex).join(", ")}] },`));
}

function emitRanges(name, list) {
	return emitTable(name, "CaseSpan", list.map(([lo, hi]) => `\t{ lo: ${hex(lo)}, hi: ${hex(hi)} },`));
}

const upper = mappings((s) => s.toUpperCase());
const lower = mappings((s) => s.toLowerCase());

process.stdout.write(`// Generated by tools/genStringCaseTables.mjs from Unicode ${process.versions.unicode} (node ${process.version}); do not edit.

export struct CaseRun {
	lo: uint32;
	hi: uint32;
	stride: uint32;
	delta: int32;
}

export struct CaseFull {
	cp: uint32;
	out: uint32[3];
}

export struct CaseSpan {
	lo: uint32;
	hi: uint32;
}

${emitRuns("upperRuns", upper.simple)}
${emitFull("upperFull", upper.full)}
${emitRuns("lowerRuns", lower.simple)}
${emitFull("lowerFull", lower.full)}
${emitRanges("casedSpans", ranges(/\p{Cased}/u))}
${emitRanges("caseIgnorableSpans", ranges(/\p{Case_Ignorable}/u))}`);
