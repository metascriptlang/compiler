// Writes runtime/core/stringCaseTables.h: the case-conversion data C's toUpperCase and toLowerCase read.
// The data is what the JS engine itself answers, so C matches JS on every code point.
// Run: node tools/genStringCaseTables.mjs > runtime/core/stringCaseTables.h

const maxCp = 0x10ffff;
const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;
const hex = (n) => "0x" + n.toString(16).toUpperCase();

function mappings(convert) {
	const simple = [];
	const full = [];
	for (let cp = 0; cp <= maxCp; cp++) {
		if (isSurrogate(cp)) continue;
		const out = [...convert(String.fromCodePoint(cp))].map((c) => c.codePointAt(0));
		if (out.length === 1 && out[0] !== cp) simple.push([cp, out[0] - cp]);
		else if (out.length > 1) full.push([cp, ...out]);
	}
	return { simple, full };
}

// A run is codepoints lo, lo+stride, ... hi that all move by the same delta.
function runs(simple) {
	const out = [];
	for (const [cp, delta] of simple) {
		const last = out[out.length - 1];
		if (last) {
			const step = last.stride === 0 ? cp - last.hi : last.stride;
			if ((step === 1 || step === 2) && cp - last.hi === step && delta === last.delta) {
				last.hi = cp;
				last.stride = step;
				continue;
			}
		}
		out.push({ lo: cp, hi: cp, stride: 0, delta });
	}
	return out.map((r) => ({ ...r, stride: r.stride === 0 ? 1 : r.stride }));
}

function ranges(pattern) {
	const out = [];
	for (let cp = 0; cp <= maxCp; cp++) {
		if (isSurrogate(cp) || !pattern.test(String.fromCodePoint(cp))) continue;
		const last = out[out.length - 1];
		if (last && last[1] === cp - 1) last[1] = cp;
		else out.push([cp, cp]);
	}
	return out;
}

function emitRuns(name, simple) {
	const rows = runs(simple).map((r) => `\t{ ${hex(r.lo)}, ${hex(r.hi)}, ${r.stride}, ${r.delta} },`);
	return `static const msCaseRun ${name}[] = {\n${rows.join("\n")}\n};\n`;
}

function emitFull(name, full) {
	const rows = full.map(([cp, ...out]) => `\t{ ${hex(cp)}, { ${[...out, ...[0, 0, 0]].slice(0, 3).map(hex).join(", ")} } },`);
	return `static const msCaseFull ${name}[] = {\n${rows.join("\n")}\n};\n`;
}

function emitRanges(name, list) {
	const rows = list.map(([lo, hi]) => `\t{ ${hex(lo)}, ${hex(hi)} },`);
	return `static const msCaseSpan ${name}[] = {\n${rows.join("\n")}\n};\n`;
}

const upper = mappings((s) => s.toUpperCase());
const lower = mappings((s) => s.toLowerCase());

process.stdout.write(`/* Generated by tools/genStringCaseTables.mjs from Unicode ${process.versions.unicode} (node ${process.version}); do not edit. */
#ifndef MS_STRING_CASE_TABLES_H
#define MS_STRING_CASE_TABLES_H

#include <stdint.h>

typedef struct { uint32_t lo, hi; int32_t stride, delta; } msCaseRun;
typedef struct { uint32_t cp; uint32_t out[3]; } msCaseFull;
typedef struct { uint32_t lo, hi; } msCaseSpan;

${emitRuns("msUpperRuns", upper.simple)}
${emitFull("msUpperFull", upper.full)}
${emitRuns("msLowerRuns", lower.simple)}
${emitFull("msLowerFull", lower.full)}
${emitRanges("msCasedSpans", ranges(/\p{Cased}/u))}
${emitRanges("msCaseIgnorableSpans", ranges(/\p{Case_Ignorable}/u))}
#endif
`);
